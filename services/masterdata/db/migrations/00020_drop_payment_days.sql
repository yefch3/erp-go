-- 客户和供应商身上的「付款账期」下线。
--
-- 它存在的唯一理由是推算到期日：合同生效时算应收到期日，下单时算应付到
-- 期日。业务把那条口径推翻了——**每一份合同、每一张采购单的到期日都是
-- 单据自己的一部分，建单时由人填**。同一个客户这一单谈 60 天、下一单要
-- 求预付，都是常事；把账期挂在客户身上，等于说和这家公司只有一种付款
-- 条件。
--
-- 两个消费者已经在同一批改动里删掉了（export 的合同生效、procurement 的
-- 下单）。留着一个没人读的数字，只会让下一个人以为它还在起作用。
--
-- 先把知识搬走，再删列。两张表本来就各有一个 payment_term 自由文本列
-- （「T/T 30 days」这种，给人看的），把配过的天数写进去——删掉的是**推算
-- 机制**，不是「这家一般给多少天」这件事本身。只在文本列为空时写，不覆盖
-- 人已经写下的话。
UPDATE customers
   SET payment_term = '账期 ' || payment_days || ' 天'
 WHERE payment_days > 0 AND btrim(payment_term) = '';

UPDATE suppliers
   SET payment_term = '账期 ' || payment_days || ' 天'
 WHERE payment_days > 0 AND btrim(payment_term) = '';

-- **这一版不删列。**
--
-- 部署顺序是「先迁库、后换容器」，健康检查失败时回滚的是容器、不是库。
-- 这一刻旧镜像还在能被回滚到的位置，而旧代码的 GetCustomer / ListCustomers
-- 都把 payment_days 写在 SELECT 列表里——列一没，客户主数据整个读不出来。
--
-- 所以按两步走：这一版把所有读写都摘干净（本批改动已经做完），列留着不动。
-- 上面那两句 UPDATE 是这一步该做的事：先把知识搬进 payment_term，免得列
-- 空着躺在那儿，谁也看不见这家一般给多少天。
--
-- **删列还差一步，而且不是「再等一版」那么简单。**（2026-08-30 查证）
--
-- CreateCustomer / GetCustomer / UpdateCustomer / UpdateCustomerProfile 和
-- 供应商那四条对应查询写的是 SELECT * / RETURNING *，而 sqlc 是在**生成时**
-- 把星号展开成写死的列清单的——所以今天跑着的二进制，发给 Postgres 的 SQL
-- 里仍然白纸黑字点着 payment_days。列一删，这八条当场报「列不存在」，
-- 客户和供应商主数据整个读不出来；而且回滚容器也救不回来。
--
-- 要真删，得先有一版把这八条改成显式列清单（不含 payment_days），那一版
-- 上线之后才轮到删列。代价是 sqlc 会从共用的 store.Customer /
-- store.Supplier 改成给每条查询单独生成行类型，app 层三十来处要跟着动一遍——
-- 而列删完之后清单又和表对上了，sqlc 会再变回共用类型，还得改回来。
--
