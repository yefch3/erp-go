package app

import (
	"context"

	"github.com/jackc/pgx/v5"
)

// EventClaim 记下「这条事件我处理了」。由事件消费者传进来，**必须在处理这条
// 事件的那个数据库事务里调用一次**。
//
// 为什么要绕这一道：认领如果单独提交，它和业务写入之间就有一道缝——进程在
// 缝里被硬杀（OOM / kill -9 / 宕机），认领留下了、活没干完，重投时就跳过一件
// 从没发生的事。一笔收货、一份生效的合同，就这么没了，而且不报错。
//
// 写进同一个事务，两者同生共死：崩溃一起回滚（重投时从头再来），提交一起落库
// （重投时安全跳过）。既不丢也不重。
//
// 类型写成裸函数而不是引用 pkg/kafkax 的类型，是为了不让业务层依赖传输层：
// 这个包不该知道事件是从 Kafka 来的。
type EventClaim func(ctx context.Context, tx pgx.Tx) error
