package app

import "strings"

// 登记一个对象 key 之前的那道检查。
//
// **这是所有服务共用一个存储桶时唯一的跨租户隔离。** 三处直传（银行流水的
// 对账单、供应商发票的扫描件、对账页上的凭证）用的是同一套编排：先签一个
// 带前缀的 key，浏览器直传，回来登记 key。登记那一步如果不认前缀，任何人
// 都能把别人租户的对象登记到自己的单据上，再从自己的页面读出来——全程没有
// 一行报错。
//
// 前缀相等还不够，还要挡住 ".."。
//
// 在 MinIO / S3 里 key 是一串不透明的字节，".." 只是一个普通的路径段，不会
// 被解析——所以 "po-recon/1/2/../../9/x" 和 "po-recon/9/x" 是两个不同的对象，
// 单看存储这一层它并不构成越权。但这个结论**依赖后端怎么处理路径**：预签名
// 地址把 key 放在 URL 的 path 里，中间只要隔着一个会规范化路径的东西（nginx、
// CDN、某个 S3 兼容网关），"以合法前缀开头" 和 "落在合法目录里" 就不再是
// 同一件事。
//
// 挡住它的代价是一行，而要靠推理证明"这条链路上没有任何一环会规范化路径"，
// 每加一个部署环节都得重新证一遍。所以这里不推理，直接拒。
func objectKeyBelongsTo(key, prefix string) bool {
	if key == "" || !strings.HasPrefix(key, prefix) {
		return false
	}
	// 拆成段来看，比 strings.Contains(key, "..") 精确：一个叫 "..pdf" 的
	// 文件名是无辜的，一个单独的 ".." 段才是要挡的。
	for _, seg := range strings.Split(key, "/") {
		if seg == ".." || seg == "." {
			return false
		}
	}
	return true
}
