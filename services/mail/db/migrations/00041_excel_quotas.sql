-- 智能转换的每月额度（计量第二步）。
--
-- 00040 把用量记下来了，于是「这个月转了多少次」有了答案。这一张表回答
-- 下一个问题：**这家公司这个月还能转多少次。** 在此之前，一家客户公司想
-- 转多少次就转多少次，而每一次都是我们这边真金白银付给模型厂的钱——一个
-- 没有上限的成本口子，只要有人写个脚本循环点，账单就没有边界。
--
-- **没有这一行 = 不限；有这一行 = 上限就是 monthly_runs。**
-- 这是这张表最要紧的一条约定。不用「0 表示不限」那种写法：0 是一个完全
-- 正当的上限值——「这家公司暂时不许用」——把它偷换成「随便用」，会在最
-- 需要拦住的时候恰好不拦。要恢复不限就删掉这一行，不是把它改成 0。
--
-- 额度按**次数**不按 token：这个数要给人看、给人填、给人解释。「本月 200
-- 次」销售听得懂，也能自己判断够不够；「本月 3000 万 token」谁也说不出
-- 那是多少封信。token 数继续记在 jobs 表上，那是给我们看成本的。
--
-- 按公司不按人：额度是我们和这家公司之间的商务约定，公司内部谁多用谁少用
-- 是他们自己的事。真需要再分到人头，是加一张表的事，不是改这一张。
CREATE TABLE mail_excel_quotas (
    tenant_id    BIGINT PRIMARY KEY,
    monthly_runs BIGINT      NOT NULL CHECK (monthly_runs >= 0),
    -- 谁改的、什么时候改的。额度是钱的事，改动要留痕；0 表示改动来自
    -- 脚本或迁移，不是某个具体的人。
    updated_by   BIGINT      NOT NULL DEFAULT 0,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

