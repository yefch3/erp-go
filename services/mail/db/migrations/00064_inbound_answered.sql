--       任何客户端回信时都会把这个标志打在原信上。只认自己那一半的话，一封
--       在手机上答过的信在这里仍然显示没答——而那恰恰是最容易被答第二遍的
--       那一封。一个偶尔说谎的标识比没有标识更坏。
--
-- 反过来也成立：我们自己发出去的回信，会给原信补一个 \Answered 推回服务器，
-- 所以在 Foxmail 里看也是答过的。两边认的是同一本账，不是各记各的。
--
-- 布尔而不是时间戳：两个来源里有一个（服务器标志）根本不带时间，非要有个
-- 时间就只能编一个。列表要的也只是「答过没有」。
