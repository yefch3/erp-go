-- 这个信箱是什么时候被解绑的。NULL = 还绑着。
--
-- **解绑不是删除。** 断的是连接：凭据清掉、不再收发、不再占用同步和常开
-- 连接的名额。**已经收到的邮件原样留着，左栏里那个箱还在，点进去照样能读
-- 能搜**，只是标着「已解绑」。
--
-- 这样定的理由：一个业务员离职、或者他不想再让 ERP 连自己的私人 Gmail，
-- 客户的往来记录不该跟着消失——那是公司的业务记录，不是他的个人物品。
-- 「连历史邮件一起彻底删掉」是另一个、更响的动作，从「已解绑」那一栏进；
-- 删邮件不可逆，不该和「我换个邮箱」挤在同一个决定里。
--
-- **为什么要单独一列，而不是从 is_active + 空凭据推。**
--
-- 推得出来，但那是隐式状态：每一个想知道「这个箱是不是解绑了」的地方都要
-- 自己拼一次条件，而拼漏的那一处不会报错——它只会把一个解绑了的箱当成
-- 还能用的。这一列还顺带回答「什么时候解的」，那是留痕要用的。
--
-- is_active 保持它原来的意思：暂停同步。解绑会一并把它置 false，但两者不是
-- 一回事——暂停之后凭据还在，随时能恢复。
ALTER TABLE mail_accounts ADD COLUMN unbound_at TIMESTAMPTZ;

-- 挑信箱的地方（全量同步、轻状态、常开连接、默认发件箱）都要跳过解绑的。
-- 这些查询本来就带 is_active，而解绑会把它置 false，所以索引照旧够用——
-- 加这一列不改变它们的选择率。
--
-- 唯一约束 UNIQUE (tenant_id, email) **有意不动**：那个地址还被这一行占着。
-- 历史邮件挂在这个账号 id 上，地址一旦被同事绑走，两段互不相干的往来就会
-- 落进同一个箱里。想彻底释放，走「彻底删除」那条路。

